import Foundation

/// Fields every transcript line with a conversation entry carries.
public struct LineMeta: Sendable, Equatable {
    public var sessionID: String?
    public var uuid: String?
    public var timestamp: Date?
    public var cwd: String?
    public var gitBranch: String?
    /// Subagent (Task/Agent tool) traffic. Lives in `<session>/subagents/*.jsonl`, `sessionId` is the parent's.
    public var isSidechain: Bool

    public init(sessionID: String? = nil, uuid: String? = nil, timestamp: Date? = nil, cwd: String? = nil, gitBranch: String? = nil, isSidechain: Bool = false) {
        self.sessionID = sessionID
        self.uuid = uuid
        self.timestamp = timestamp
        self.cwd = cwd
        self.gitBranch = gitBranch
        self.isSidechain = isSidechain
    }
}

public struct ToolResult: Sendable, Equatable {
    public var toolUseID: String
    public var isError: Bool
}

public struct ToolUse: Sendable, Equatable {
    public var id: String
    public var name: String
    /// `file_path` / `notebook_path` input, when present.
    public var filePath: String?

    /// Tools that change files on disk.
    public var changesFile: Bool { ToolUse.fileChangingTools.contains(name) }
    static let fileChangingTools: Set<String> = ["Edit", "MultiEdit", "Write", "NotebookEdit"]
}

public struct UserEntry: Sendable, Equatable {
    public var meta: LineMeta
    /// Injected by Claude Code (caveats, skill bodies), not typed by the person.
    public var isMeta: Bool
    /// Joined text blocks or the string content. Nil when the line only carries tool results.
    public var text: String?
    public var toolResults: [ToolResult]

    /// A prompt the person typed: text that is not meta and not a Claude Code wrapper such as
    /// `<command-name>`, `<local-command-stdout>` or `<task-notification>`.
    public var isPrompt: Bool {
        guard !isMeta, !meta.isSidechain, let text, !text.isEmpty else { return false }
        if text.hasPrefix("[Request interrupted") { return false }
        return !UserEntry.startsWithWrapperTag(text)
    }

    static func startsWithWrapperTag(_ s: String) -> Bool {
        var it = s.utf8.makeIterator()
        guard it.next() == UInt8(ascii: "<") else { return false }
        var n = 0
        while let c = it.next() {
            if c == UInt8(ascii: ">") || c == UInt8(ascii: " ") { return n > 0 }
            let letter = c >= 97 && c <= 122
            let ok = n == 0 ? letter : (letter || c == UInt8(ascii: "-") || c == UInt8(ascii: "_") || (c >= 48 && c <= 57))
            if !ok { return false }
            n += 1
        }
        return false
    }
}

public struct AssistantEntry: Sendable, Equatable {
    public var meta: LineMeta
    public var messageID: String
    public var requestID: String?
    public var model: String
    public var usage: TokenUsage
    public var text: String?
    public var toolUses: [ToolUse]

    /// Key used to count a streamed message once across lines, files and refreshes.
    public var dedupeKey: String { requestID.map { messageID + ":" + $0 } ?? messageID }
}

public struct TitleEntry: Sendable, Equatable {
    public enum Kind: Int, Sendable, Comparable {
        /// Generated by Claude Code (`ai-title`).
        case ai = 1
        /// Older `summary` lines (keyed by `leafUuid`, no `sessionId`).
        case summary = 2
        /// Set by the person with `/rename` (`custom-title`).
        case custom = 3
        public static func < (a: Kind, b: Kind) -> Bool { a.rawValue < b.rawValue }
    }
    public var kind: Kind
    public var text: String
    public var sessionID: String?
}

public enum TranscriptEvent: Sendable, Equatable {
    case user(UserEntry)
    case assistant(AssistantEntry)
    case title(TitleEntry)
}
